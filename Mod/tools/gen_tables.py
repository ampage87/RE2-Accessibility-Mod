"""Generates src/tables.inc (item names, enemy names, ammo map, script opcode sizes, message
character table) from the simulator's tables, so the mod and the simulator share one source.

Run from the re2mod folder:  python tools/gen_tables.py ../Simulator   (or ../re2sim)
"""
import os
import re
import sys

sim = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..", "..", "Simulator")
sys.path.insert(0, os.path.abspath(sim))
from re2sim import scd                      # noqa: E402
from re2sim.rdt import MSG_TABLE            # noqa: E402


def human(raw):
    s = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", " ", raw)
    s = re.sub(r"(?<=[A-Z])(?=[A-Z][a-z])", " ", s)
    return s[:1].upper() + s[1:].lower() if s else s


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


items = []
for i, raw in enumerate(scd.ITEM_IDS):
    if not raw or raw == "None":
        items.append("")
    else:
        items.append(scd.ITEM_DISPLAY.get(raw) or human(raw))
enemies = []
for i, raw in enumerate(scd.ENEMY_IDS):
    enemies.append(raw or "")

out = ["// Generated by tools/gen_tables.py from the simulator's tables. Do not edit by hand.",
       "#pragma once", ""]
out.append(f"static const char* const kItemNames[{len(items)}] = {{")
out += [f"    {cstr(n)},  // {i}" for i, n in enumerate(items)]
out.append("};")
out.append(f"static const int kItemCount = {len(items)};")
out.append("")
out.append(f"static const char* const kEnemyNames[{len(enemies)}] = {{")
out += [f"    {cstr(n)},  // 0x{i:02X}" for i, n in enumerate(enemies)]
out.append("};")
out.append(f"static const int kEnemyCount = {len(enemies)};")
out.append("")
out.append("// weapon item id -> ammunition item id")
out.append("static const unsigned char kAmmoFor[][2] = {")
out += [f"    {{{w}, {a}}}," for w, a in sorted(scd.AMMO_FOR.items())]
out.append("};")
out.append("")
out.append("// script opcode sizes (bytes), from BioRand's Bio2ConstantTable")
out.append(f"static const unsigned char kOpSize[{len(scd.SIZES)}] = {{")
out.append("    " + ", ".join(str(x) for x in scd.SIZES))
out.append("};")
names = {n: i for i, n in enumerate(scd.NAMES)}
for n in ("aot_set", "aot_set_4p", "door_aot_se", "door_aot_set_4p", "item_aot_set", "item_aot_set_4p",
          "message_on", "aot_reset"):
    out.append(f"static const int OP_{n.upper()} = {names[n]};")
out.append("")
out.append("// message character table (English), index = byte value; empty = unmapped glyph")
glyph = {"\u201c": '\\"', "\u201d": '\\"'}
cells = []
for ch in MSG_TABLE:
    if ch == "_":
        cells.append('""')
    elif ch in glyph:
        cells.append('"\\""')
    else:
        cells.append(cstr(ch))
out.append(f"static const char* const kMsgChars[{len(cells)}] = {{" + ", ".join(cells) + "};")
out.append(f"static const int kMsgCharCount = {len(cells)};")
out.append("")
dst = os.path.join(os.path.dirname(__file__), "..", "src", "tables.inc")
with open(dst, "w", encoding="utf-8") as f:
    f.write("\n".join(out) + "\n")
print("wrote", os.path.abspath(dst), len(items), "items", len(enemies), "enemy types")
